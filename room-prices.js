// ---- 방 가격 원장 불러오기 ----
// 대시보드와 같은 값을 쓰기 위해 Firestore의 공개 문서 하나를 읽는다. SDK를 붙이면 페이지가
// 무거워져서, 인증이 필요 없는 REST 엔드포인트를 fetch로 직접 호출한다(문서 1건 읽기).
// 실패하면 위의 예비값을 그대로 쓰므로 계산기는 어떤 경우에도 동작한다.
const ROOM_PRICES_URL = 'https://firestore.googleapis.com/v1/projects/monthliv-482bd/databases/(default)/documents/monthliv/roomPrices';

function unwrapFirestore(v) {
  if (!v || typeof v !== 'object') return v;
  if ('stringValue' in v) return v.stringValue;
  if ('integerValue' in v) return parseInt(v.integerValue, 10);
  if ('doubleValue' in v) return Number(v.doubleValue);
  if ('booleanValue' in v) return v.booleanValue;
  if ('nullValue' in v) return null;
  if ('arrayValue' in v) return (v.arrayValue.values || []).map(unwrapFirestore);
  if ('mapValue' in v) {
    const o = {};
    for (const k in (v.mapValue.fields || {})) o[k] = unwrapFirestore(v.mapValue.fields[k]);
    return o;
  }
  return v;
}

// 원장을 읽어 ROOMS를 교체한 뒤 onLoaded를 불러 화면(지점·호실 목록)을 다시 채우게 한다.
async function loadRoomPrices(onLoaded) {
  try {
    const res = await fetch(ROOM_PRICES_URL, { cache: 'no-store' });
    if (!res.ok) return;                       // 문서가 아직 없거나 읽기 권한이 없으면 예비값 유지
    const doc = await res.json();
    const rooms = unwrapFirestore((doc.fields || {}).rooms);
    if (!Array.isArray(rooms) || rooms.length === 0) return;
    ROOMS = rooms;
    if (onLoaded) onLoaded();
  } catch (e) {
    // 예비값으로 계속 동작한다 — 계산기가 멈추는 것보다 낫다.
    console.error('방 가격 원장을 불러오지 못해 내장된 예비값을 사용합니다:', e);
  }
}

// ---- 조회 ----
function roomBranches() {
  return [...new Set(ROOMS.map(x => x.b))];
}

// 룸타입은 고르지 않고 지점에서 호실을 바로 고른다. 여러 룸타입 행에 흩어진 호실을
// 한 목록으로 모아 번호순으로 정렬한다.
function roomNumbersOf(branch) {
  const nums = ROOMS.filter(x => x.b === branch).flatMap(x => x.nums || []);
  return [...new Set(nums)].sort((a, b) => String(a).localeCompare(String(b), 'ko', { numeric: true }));
}

// 가격은 고른 호실이 들어있는 행에서 가져온다. 같은 룸타입이라도 호실마다 가격이 다른
// 지점이 있어서(구로 트리니티B 등) 룸타입으로 찾으면 금액이 틀린다.
function roomRowOf(branch, num) {
  return ROOMS.find(x => x.b === branch && (x.nums || []).includes(num)) || null;
}

// 시기에 따라 입실료가 바뀌는 방(방배 이수역 7~9월 등)은 기준일이 속한 달로 고른다.
function roomP1For(row, date) {
  if (!row) return 0;
  const months = Array.isArray(row.altMonths) ? row.altMonths : [];
  if (!row.p1Alt || months.length === 0) return row.p1 || 0;
  const m = (date || new Date()).getMonth() + 1;
  return months.includes(m) ? row.p1Alt : (row.p1 || 0);
}
